def _두자리해(yy):
    """두 자리 연도를 네 자리로. 2026 년이라 26 이상은 1900 년대로 본다."""
    return 1900 + yy if yy >= 26 else 2000 + yy


def 생년월일(글):
    """생년월일을 뽑는다. 못 찾으면 None.

    실제 댓글에서 나온 꼴을 전부 받는다
        940426 / 19940426 / 94.04.26 / 1994.4.26 / 94년 4월 26일 / 1994 04 26

    **시각과 헷갈리지 않게** 한다. "13시 07분" 의 숫자를 날짜로 주우면 안 된다.
    """
    t = 글 or ""

    # ① 년·월·일 글자가 붙은 꼴이 제일 확실하다
    m = re.search(r"(\d{2,4})\s*년\s*(\d{1,2})\s*월\s*(\d{1,2})\s*일?", t)
    if m:
        y, mo, d = int(m.group(1)), int(m.group(2)), int(m.group(3))
        if y < 100:
            y = _두자리해(y)
        if 1 <= mo <= 12 and 1 <= d <= 31:
            return y, mo, d

    # ② 점·빗금·하이픈으로 끊은 꼴
    m = re.search(r"(?<!\d)(\d{2,4})\s*[.\-/]\s*(\d{1,2})\s*[.\-/]\s*(\d{1,2})(?!\d)", t)
    if m:
        y, mo, d = int(m.group(1)), int(m.group(2)), int(m.group(3))
        if y < 100:
            y = _두자리해(y)
        if 1 <= mo <= 12 and 1 <= d <= 31:
            return y, mo, d

    # ③ 붙여 쓴 6자리·8자리
    for m in re.finditer(r"(?<!\d)(\d{6}|\d{8})(?!\d)", t):
        덩어리 = m.group(1)
        # 바로 뒤가 '시'·'분'이면 시각이다
        뒤 = t[m.end():m.end() + 2]
        if 뒤.strip()[:1] in ("시", "분"):
            continue
        if len(덩어리) == 8:
            y, mo, d = int(덩어리[:4]), int(덩어리[4:6]), int(덩어리[6:])
        else:
            y, mo, d = _두자리해(int(덩어리[:2])), int(덩어리[2:4]), int(덩어리[4:])
        if 1 <= mo <= 12 and 1 <= d <= 31 and 1900 <= y <= 올해:
            return y, mo, d

    # ④ 띄어 쓴 꼴 — "1982 12 14"
    m = re.search(r"(?<!\d)(19\d{2}|20\d{2})\s+(\d{1,2})\s+(\d{1,2})(?!\d)", t)
    if m:
        y, mo, d = int(m.group(1)), int(m.group(2)), int(m.group(3))
        if 1 <= mo <= 12 and 1 <= d <= 31:
            return y, mo, d
    return None


def 생년만(글):
    """월일 없이 연도만 적어 온 경우. 미성년 거르기에만 쓴다."""
    m = re.search(r"(?<!\d)(19\d{2}|20\d{2})\s*년?\s*생?", 글 or "")
    if m:
        return int(m.group(1))
    m = re.search(r"(?<!\d)(\d{2})\s*년\s*생", 글 or "")
    if m:
        return _두자리해(int(m.group(1)))
    return None


def 시각(글):
    """시각. 없으면 None. 시간을 모른다고 했으면 건드리지 않는다."""
    t = 글 or ""
    if re.search(r"시\s*(간|각)?\s*(몰라|모름|모르|기억\s*안)", t):
        return None
    m = re.search(r"([자축인묘진사오미신유술해])\s*시(?!\s*(간|각))", t)
    if m:
        return 지지시[m.group(1)], 0
    m = re.search(r"(오전|오후|새벽|아침|낮|저녁|밤)?\s*(?<!\d)(\d{1,2})\s*[-~]\s*(\d{1,2})\s*시", t)
    if m:
        h = (int(m.group(2)) + int(m.group(3))) // 2
        if m.group(1) in ("오후", "저녁", "밤") and h < 12:
            h += 12
        return h % 24, 0
    m = re.search(r"(오전|오후|새벽|아침|낮|저녁|밤)?\s*(?<!\d)(\d{1,2})\s*[:시]\s*(\d{1,2})?\s*분?", t)
    if m:
        h, mi = int(m.group(2)), int(m.group(3) or 0)
        if m.group(1) in ("오후", "저녁", "밤") and h < 12:
            h += 12
        if 0 <= h <= 24 and 0 <= mi < 60:
            return h % 24, mi
    return None


# 남의 사주를 같이 적을 때 쓰는 말. 이게 있으면 성별을 안 건진다(누구 것인지 모른다)
남얘기 = re.compile(r"(상대|그\s*사람|남친|여친|남편|아내|와이프|전남|전여|애인|배우자|둘\s*다|두\s*사람)")


def 성별(글):
    """'여' 한 글자도 잡는다. 두 사람 얘기면 손대지 않는다."""
    t = 글 or ""
    if 남얘기.search(t):
        return ""
    남 = re.search(r"(남자|남성|남임|남이야|male|(?<![가-힣])남(?![가-힣]))", t)
    여 = re.search(r"(여자|여성|여임|여야|female|(?<![가-힣])여(?![가-힣]))", t)
    if bool(남) == bool(여):
        return ""
    return "M" if 남 else "F"


def 양음력(글):
    """양력/음력. 안 적었으면 양력으로 본다 (엔진 기본값과 같다)."""
    t = 글 or ""
    if re.search(r"(음력|음\s*력|\(음\)|\(음력\)|(?<![가-힣])음(?![가-힣악성]))", t):
        return "lunar"
    return "solar"


def 미성년인가(글, 생년):
    """**애매하면 True.** 잘못 막으면 답글 하나가 안 나갈 뿐이고,
    잘못 통과시키면 미성년에게 사주를 봐 주게 된다 (개인정보보호법 만 14세)."""
    t = (글 or "").replace(" ", "")
    for 말 in 미성년말:
        if 말.replace(" ", "") in t:
            return True
    if 생년 and 생년 >= 미성년생년:
        return True
    return False


def 어떻게(글, 생년월일있나):
    """이 댓글을 어떻게 할까 — 답함 / 무시 / 보류.

    **보류는 사람한테 넘긴다.** 기계가 애매하게 답하느니 안 답하는 게 낫다.
    """
    t = (글 or "").strip()
    민 = t.replace(" ", "")
    if len(민) < 4:
        return "무시", "너무 짧다"
    if re.search(r"https?://|\.com|\.kr(?![가-힣])", t):
        return "무시", "링크"
    if not re.search(r"[가-힣]", t):
        return "무시", "한글이 없다"
    if 민 in 껍데기 or (len(민) <= 8 and any(민.startswith(x) for x in 껍데기)):
        return "무시", "인사·감사"
    for 말 in 악의말:
        if 말 in 민:
            return "보류", "시비로 보인다: " + 말
    for 말 in 동업자말:
        if 말.replace(" ", "") in 민:
            return "보류", "동업자로 보인다: " + 말
    if not 생년월일있나:
        return "무시", "생년월일이 없다"
    return "답함", ""


def 뽑기(글):
    """댓글 하나에서 전부 뽑는다. AI 를 한 번도 안 부른다."""
    t = 글 or ""
    날 = 생년월일(t)
    해 = 날[0] if 날 else 생년만(t)
    때 = 시각(t)
    것 = {
        "year": 날[0] if 날 else -1,
        "month": 날[1] if 날 else -1,
        "day": 날[2] if 날 else -1,
        "hour": 때[0] if 때 else -1,
        "minute": 때[1] if 때 else -1,
        "gender": 성별(t),
        "calendar": 양음력(t),
        "minor": 미성년인가(t, 해),
        "worry": t[:120],
        "만든법": "파이썬",
    }
    라벨, 까닭 = 어떻게(t, bool(날))
    if 것["minor"]:
        라벨, 까닭 = "무시", "미성년으로 보인다"
    것["label"], 것["reason"] = 라벨, 까닭
    것["confidence"] = 100 if 라벨 == "답함" else 0
    return 것


